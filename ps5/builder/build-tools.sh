#!/usr/bin/env bash
# Luigi's Mansion for the PlayStation 5 - the builder's own programs, for Linux or Windows.
#
#   ps5/builder/build-tools.sh linux|windows VERSION     -> build/builder-tools/<platform>/
#
# Made on Linux (or WSL2): Windows' are cross-compiled with MinGW-w64, so no Windows toolchain
# is needed. Each is static (glibc aside on Linux), so the zips run without installing anything:
#
#   Luigi's Mansion PS5 Builder[.exe]   the app (ps5/builder/app: SDL3 + Dear ImGui)
#   lm-builder[.exe]                    the builder (ps5/builder/builder.cpp)
#   lmrecompile[.exe]                   lm-recomp's recompiler (vendor/luigis-mansion-recompiled)
#   ps5-native-tool[.exe]               PS5_Vulkan's ELF -> PS5 executable tool
#   nodtool[.exe]                       encounter/nod's disc tool (cargo)
#
# Needs ps5/builder/fetch-app-deps.sh first (SDL, imgui, fonts, MinGW).
#
# SPDX-License-Identifier: MIT
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
platform=${1:?usage: build-tools.sh linux|windows VERSION}
version=${2:?usage: build-tools.sh linux|windows VERSION}
deps="$root/.deps/app"
lm="$root/vendor/luigis-mansion-recompiled"
vulkan=$(cd -- "${PS5_VULKAN_DIR:-$root/../PS5_Vulkan}" && pwd)
out="$root/build/builder-tools/$platform"
work="$root/build/builder-work/$platform"
app_name="Luigi's Mansion PS5 Builder"
mkdir -p "$out" "$work"
bash "$root/ps5/tools/setup-source.sh"

case $platform in
linux)
    cxx="clang++"
    cc="clang"
    exe=""
    static_flags=(-static-libstdc++ -static-libgcc)
    cmake_toolchain=()
    ;;
windows)
    cxx="x86_64-w64-mingw32-g++-posix"
    cc="x86_64-w64-mingw32-gcc-posix"
    exe=".exe"
    static_flags=(-static -static-libstdc++ -static-libgcc)
    cmake_toolchain=(-DCMAKE_TOOLCHAIN_FILE="$deps/SDL/build-scripts/cmake-toolchain-mingw64-x86_64.cmake")
    ;;
*) echo "build-tools.sh: linux or windows" >&2; exit 2 ;;
esac

# SDL3, static
sdl_prefix="$work/sdl-install"
if [[ ! -f $sdl_prefix/lib/libSDL3.a ]]; then
    cmake -S "$deps/SDL" -B "$work/sdl" -G Ninja "${cmake_toolchain[@]}" -DCMAKE_BUILD_TYPE=Release \
        -DSDL_STATIC=ON -DSDL_SHARED=OFF -DSDL_TEST_LIBRARY=OFF -DSDL_TESTS=OFF -DSDL_EXAMPLES=OFF \
        -DSDL_CAMERA=OFF -DSDL_HAPTIC=OFF -DSDL_SENSOR=OFF -DSDL_JOYSTICK=OFF -DSDL_HIDAPI=OFF \
        -DCMAKE_POSITION_INDEPENDENT_CODE=ON -DCMAKE_INSTALL_PREFIX="$sdl_prefix" > "$work/sdl-configure.log"
    cmake --build "$work/sdl" > "$work/sdl-build.log"
    cmake --install "$work/sdl" > /dev/null
fi
sdl_libs=$(PKG_CONFIG_PATH="$sdl_prefix/lib/pkgconfig" pkg-config --static --libs sdl3)

# The fonts, into the app (app_fonts.h)
python3 - "$deps/fonts" "$work/app_fonts.h" <<'EOF'
import pathlib, sys
fonts, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
parts = ["// Generated by ps5/builder/build-tools.sh: the app's fonts (licences in licenses/)\n#pragma once\n"]
for name, file in (("kCreepster", "Creepster-Regular.ttf"), ("kDejaVuSans", "DejaVuSans.ttf"), ("kDejaVuSansBold", "DejaVuSans-Bold.ttf")):
    data = (fonts / file).read_bytes()
    rows = ",\n".join(",".join(str(b) for b in data[i:i + 40]) for i in range(0, len(data), 40))
    parts.append(f"static const unsigned char {name}[] = {{\n{rows}\n}};\n")
out.write_text("".join(parts))
EOF

# The app
imgui="$deps/imgui"
app_sources=("$root/ps5/builder/app/app.cpp" "$imgui/imgui.cpp" "$imgui/imgui_draw.cpp" "$imgui/imgui_tables.cpp"
    "$imgui/imgui_widgets.cpp" "$imgui/backends/imgui_impl_sdl3.cpp" "$imgui/backends/imgui_impl_sdlrenderer3.cpp")
app_flags=(-std=c++20 -O2 -DLM_BUILDER_VERSION="\"$version\"" -I"$imgui" -I"$imgui/backends" -I"$sdl_prefix/include" -I"$work")
if [[ $platform == windows ]]; then
    # The icon and version resource, and a window app (no console)
    python3 "$root/ps5/builder/app/make-app-icon.py" "$work/app.ico"
    cat > "$work/app.rc" <<EOF
1 ICON "app.ico"
1 VERSIONINFO
FILEVERSION 1,0,0,0
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "FileDescription", "$app_name"
      VALUE "ProductName", "$app_name"
      VALUE "ProductVersion", "$version"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
EOF
    (cd "$work" && x86_64-w64-mingw32-windres app.rc -O coff -o app_res.o)
    "$cxx" "${app_flags[@]}" "${app_sources[@]}" "$work/app_res.o" -o "$out/$app_name.exe" -mwindows \
        "${static_flags[@]}" $sdl_libs
else
    "$cxx" "${app_flags[@]}" "${app_sources[@]}" -o "$out/$app_name" "${static_flags[@]}" $sdl_libs
fi

# The builder
"$cxx" -std=c++20 -O2 "$root/ps5/builder/builder.cpp" -o "$out/lm-builder$exe" "${static_flags[@]}"
# lm-recomp's recompiler
"$cxx" -std=c++20 -O2 -I "$lm/src" "$lm/tools/recomp/lmrecompile.cpp" "$lm/src/recompiler/recompiler.cpp" \
    -o "$out/lmrecompile$exe" "${static_flags[@]}"
# PS5_Vulkan's native tool, with zlib built in
zlib="$root/.deps/zlib"
if [[ ! -f $zlib/zlib.h ]]; then
    mkdir -p "$zlib"
    curl -sSL https://github.com/madler/zlib/releases/download/v1.3.1/zlib-1.3.1.tar.gz | tar -xz -C "$zlib" --strip-components 1
fi
mkdir -p "$work/zlib"
zobjects=()
# (compression only: the native tool reads and writes no .gz files)
for source in adler32 compress crc32 deflate infback inffast inflate inftrees trees uncompr zutil; do
    "$cc" -O2 -c "$zlib/$source.c" -I "$zlib" -o "$work/zlib/$source.o"
    zobjects+=("$work/zlib/$source.o")
done
native="$vulkan/tooling/native"
"$cxx" -std=c++20 -O2 -I "$zlib" "$native/native_app_builder.cpp" "$native/self_container.cpp" "$native/elf_object.cpp" \
    "$native/sce_module_writer.cpp" "${zobjects[@]}" -o "$out/ps5-native-tool$exe" "${static_flags[@]}"
# nod's disc tool
cargo="$HOME/.cargo/bin/cargo"
if [[ $platform == windows ]]; then
    "$HOME/.cargo/bin/rustup" target add x86_64-pc-windows-gnu > /dev/null 2>&1
    CARGO_TARGET_X86_64_PC_WINDOWS_GNU_LINKER=x86_64-w64-mingw32-gcc-posix \
        CC_x86_64_pc_windows_gnu=x86_64-w64-mingw32-gcc-posix AR_x86_64_pc_windows_gnu=x86_64-w64-mingw32-ar \
        "$cargo" install --locked --quiet nodtool --target x86_64-pc-windows-gnu --root "$work/cargo"
else
    "$cargo" install --locked --quiet nodtool --root "$work/cargo"
fi
cp "$work/cargo/bin/nodtool$exe" "$out/nodtool$exe"
ls -la "$out"
